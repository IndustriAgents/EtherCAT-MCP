from __future__ import annotations

from typing import Any, Protocol


class EthercatMasterPort(Protocol):
    config: Any

    def shutdown_calls(self, reason: Any) -> Any: ...

    def describe(self) -> Any: ...

    def require_writes(self) -> Any: ...

    def require_state_changes(self) -> Any: ...

    async def scan_slaves(self) -> Any: ...

    async def get_slave(self, position: Any) -> Any: ...

    async def read_pdo(self, position: Any, offset: Any, length: Any) -> Any: ...

    async def write_pdo(self, position: Any, offset: Any, data: Any) -> Any: ...

    async def read_sdo(self, position: Any, index: Any, subindex: Any, max_bytes: Any = 256) -> Any: ...

    async def write_sdo(self, position: Any, index: Any, subindex: Any, data: Any) -> Any: ...

    async def set_slave_state(self, position: Any, state: Any) -> Any: ...

    async def test_communication(self, position: Any) -> Any: ...

    def connection_status(self) -> Any: ...

    async def close(self) -> Any: ...
